import 'dart:typed_data';
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import '../core/constants/app_constants.dart';
import '../core/utils/app_formatter.dart';
import '../core/utils/tax_hints.dart';
import '../models/tax_profile.dart';

/// Print-ready PAYE assessment report, focused on one calculation:
/// key figures → how taxable income was worked out → the user's bands
/// (with a plain-English marginal-band explanation) → all 2025 bands
/// as a reference → optional CIT note → disclaimer.
class PdfService {

  static const _primary = PdfColor.fromInt(0xFF00288E);
  static const _grey = PdfColor.fromInt(0xFF444653);
  static const _line = PdfColor.fromInt(0xFFC4C5D5);
  static const _red = PdfColor.fromInt(0xFFB91C1C);
  static const _green = PdfColor.fromInt(0xFF15803D);
  static const _softBg = PdfColor.fromInt(0xFFF1F3FF);

  static Future<Uint8List> generateTaxReportBytes(
    TaxProfile profile, {
    String? userName,
  }) async {
    final doc = pw.Document();
    final font = await PdfGoogleFonts.interRegular();
    final boldFont = await PdfGoogleFonts.interBold();

    final displayDate = profile.createdAt ?? DateTime.now();
    final preparedFor = (userName ?? '').trim();

    // ── Derivations ─────────────────────────────────────────────────────────
    final pensionRatePct = profile.annualGross > 0
        ? (profile.pensionDeduction / profile.annualGross) * 100
        : 0.0;
    final isFlat = profile.breakdown.isNotEmpty &&
        profile.breakdown.first.bracket.startsWith('Flat');
    final crossedBands =
        profile.breakdown.where((b) => b.taxableAmount > 0 || b.tax > 0).toList();
    final topBand = crossedBands.isNotEmpty ? crossedBands.last : null;
    final marginalRatePct = isFlat
        ? (topBand?.rate ?? 0) * 100
        : ((topBand?.rate ?? 0) * 100);
    final topBandRange = isFlat ? null : _rangeForRate(marginalRatePct);

    pw.TextStyle t({bool bold = false, double size = 11, PdfColor? color}) =>
        pw.TextStyle(
          font: bold ? boldFont : font,
          fontSize: size,
          color: color ?? PdfColors.black,
        );

    doc.addPage(
      pw.MultiPage(
        theme: pw.ThemeData.withFont(base: font, bold: boldFont),
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        header: (_) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(AppConstants.appName,
                    style: pw.TextStyle(font: boldFont, fontSize: 18, color: _primary)),
                pw.Text('Personal Income Tax Assessment (PAYE)',
                    style: pw.TextStyle(font: font, fontSize: 11, color: _grey)),
              ],
            ),
            pw.Divider(color: _line),
          ],
        ),
        footer: (_) => pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(
                'Generated by ${AppConstants.appName} · ${DateFormat.yMMMd().format(DateTime.now())}',
                style: pw.TextStyle(fontSize: 9, font: font, color: _grey)),
            pw.Text('For educational purposes only. Not official tax advice.',
                style: pw.TextStyle(fontSize: 9, font: font, color: _grey)),
          ],
        ),
        build: (_) => [
          pw.SizedBox(height: 14),

          // ── Title block ────────────────────────────────────────────────
          pw.Text('Tax Assessment Report',
              style: pw.TextStyle(font: boldFont, fontSize: 20, color: PdfColors.black)),
          pw.SizedBox(height: 4),
          pw.Row(
            children: [
              pw.Text(
                preparedFor.isNotEmpty ? 'Prepared for: $preparedFor' : 'Personal assessment',
                style: pw.TextStyle(fontSize: 12, font: font, color: _grey),
              ),
              pw.Text('   ·   ', style: pw.TextStyle(fontSize: 12, font: font, color: _line)),
              pw.Text(
                'Assessment date: ${DateFormat('d MMMM yyyy').format(displayDate)}',
                style: pw.TextStyle(fontSize: 12, font: font, color: _grey),
              ),
            ],
          ),
          pw.SizedBox(height: 14),

          // ── Hero summary ───────────────────────────────────────────────
          pw.Container(
            padding: const pw.EdgeInsets.all(14),
            decoration: pw.BoxDecoration(
              color: _softBg,
              borderRadius: const pw.BorderRadius.all(pw.Radius.circular(10)),
              border: pw.Border.all(color: _primary, width: 0.8),
            ),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Row(
                  children: [
                    _heroCell('Annual gross income', AppFormatter.naira(profile.annualGross),
                        PdfColors.black, t),
                    _heroCell('Total tax payable', AppFormatter.naira(profile.computedTax),
                        _red, t),
                    _heroCell('Monthly tax (PAYE)', AppFormatter.naira(profile.computedTax / 12),
                        _red, t),
                    _heroCell('Annual take-home', AppFormatter.naira(profile.netIncome),
                        _green, t, isLast: true),
                  ],
                ),
                pw.SizedBox(height: 10),
                pw.Divider(color: _line),
                pw.SizedBox(height: 6),
                pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text(
                      'Effective tax rate: ${profile.effectiveTaxRate.toStringAsFixed(1)}% of gross income',
                      style: t(bold: true, size: 10, color: _primary),
                    ),
                    pw.Text(
                      'You save ${AppFormatter.naira(profile.savings)} vs. the old tax regime',
                      style: t(bold: true, size: 10, color: _green),
                    ),
                  ],
                ),
              ],
            ),
          ),
          pw.SizedBox(height: 16),

          // ── How taxable income was worked out ──────────────────────────
          pw.Text('How we worked out your taxable income',
              style: pw.TextStyle(font: boldFont, fontSize: 13)),
          pw.SizedBox(height: 6),
          _stepRow('Annual gross income', AppFormatter.naira(profile.annualGross), t),
          _stepRow(
            'Less: pension deduction (${pensionRatePct.toStringAsFixed(0)}% of gross)',
            '- ${AppFormatter.naira(profile.pensionDeduction)}',
            t,
          ),
          _stepRow(
            profile.rentRelief > 0
                ? 'Less: rent relief (20% of rent paid, capped at ₦500,000)'
                : 'Less: rent relief (none claimed)',
            '- ${AppFormatter.naira(profile.rentRelief)}',
            t,
          ),
          pw.Container(
            margin: const pw.EdgeInsets.only(top: 4),
            padding: const pw.EdgeInsets.symmetric(vertical: 6, horizontal: 8),
            decoration: pw.BoxDecoration(
              color: _softBg,
              borderRadius: const pw.BorderRadius.all(pw.Radius.circular(6)),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text('Taxable income', style: t(bold: true, size: 12)),
                pw.Text(AppFormatter.naira(profile.taxableIncome), style: t(bold: true, size: 12)),
              ],
            ),
          ),
          pw.SizedBox(height: 16),

          // ── The user's bands ───────────────────────────────────────────
          if (isFlat) ...[
            pw.Container(
              padding: const pw.EdgeInsets.all(12),
              decoration: pw.BoxDecoration(
                color: _softBg,
                borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
                border: pw.Border.all(color: _primary, width: 0.6),
              ),
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text('Flat rate selected: ${marginalRatePct.toStringAsFixed(0)}%',
                      style: pw.TextStyle(font: boldFont, fontSize: 13, color: _primary)),
                  pw.SizedBox(height: 4),
                  pw.Text(
                    'You chose a flat ${marginalRatePct.toStringAsFixed(0)}% rate, applied to your '
                    'entire taxable income of ${AppFormatter.naira(profile.taxableIncome)}. '
                    'This figure is not band-progressive.',
                    style: t(size: 10, color: _grey),
                  ),
                ],
              ),
            ),
          ] else ...[
            pw.Text('Your tax bands', style: pw.TextStyle(font: boldFont, fontSize: 13)),
            pw.SizedBox(height: 4),
            pw.Text(
              topBand != null
                  ? 'You are in the ${marginalRatePct.toStringAsFixed(0)}% band'
                      '${topBandRange != null ? ' (taxable income between $topBandRange)' : ''}. '
                      'Only the income that falls inside each band is taxed at that band\u2019s rate — '
                      'your whole income is never taxed at your top rate.'
                  : 'Your taxable income falls entirely within the first ₦800,000, which is taxed at 0%.',
              style: t(size: 10, color: _grey),
            ),
            pw.SizedBox(height: 8),
            pw.Table(
              columnWidths: {
                0: const pw.FlexColumnWidth(3),
                1: const pw.FlexColumnWidth(1.4),
                2: const pw.FlexColumnWidth(2.6),
                3: const pw.FlexColumnWidth(2.2),
              },
              children: [
                pw.TableRow(
                  decoration: const pw.BoxDecoration(color: PdfColor.fromInt(0xFF00288E)),
                  children: ['Band', 'Rate', 'Your income in this band', 'Tax at this rate']
                      .map((h) => pw.Padding(
                            padding: const pw.EdgeInsets.all(6),
                            child: pw.Text(h,
                                style: pw.TextStyle(
                                    font: boldFont, fontSize: 10, color: PdfColors.white)),
                          ))
                      .toList(),
                ),
                ...crossedBands.map((b) {
                  final label = b.bracket.replaceFirst(RegExp(r'\s*@\s*\d+(\.\d+)?%$'), '');
                  final isTop = b == topBand;
                  return pw.TableRow(
                    decoration: isTop
                        ? pw.BoxDecoration(color: _softBg)
                        : const pw.BoxDecoration(),
                    children: [
                      pw.Padding(
                        padding: const pw.EdgeInsets.all(6),
                        child: pw.Text(label, style: t(bold: isTop, size: 10)),
                      ),
                      pw.Padding(
                        padding: const pw.EdgeInsets.all(6),
                        child: pw.Text('${(b.rate * 100).toStringAsFixed(0)}%',
                            style: t(bold: true, size: 10, color: _primary)),
                      ),
                      pw.Padding(
                        padding: const pw.EdgeInsets.all(6),
                        child: pw.Text(AppFormatter.naira(b.taxableAmount), style: t(size: 10)),
                      ),
                      pw.Padding(
                        padding: const pw.EdgeInsets.all(6),
                        child: pw.Text(AppFormatter.naira(b.tax), style: t(size: 10)),
                      ),
                    ],
                  );
                }),
              ],
            ),
            pw.SizedBox(height: 6),
            pw.Row(
              children: [
                pw.Container(
                  width: 10,
                  height: 10,
                  decoration: const pw.BoxDecoration(color: PdfColor.fromInt(0xFFF1F3FF)),
                ),
                pw.SizedBox(width: 6),
                pw.Text('Shaded row = your top band (marginal band)',
                    style: t(size: 9, color: _grey)),
              ],
            ),
          ],
          pw.SizedBox(height: 16),

          // ── Why these rates? ───────────────────────────────────────────
          pw.Container(
            padding: const pw.EdgeInsets.all(12),
            decoration: pw.BoxDecoration(
              color: _softBg,
              borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
            ),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text('Why these rates?', style: pw.TextStyle(font: boldFont, fontSize: 12)),
                pw.SizedBox(height: 4),
                pw.Text(
                  'Under the 2025 Nigeria Tax Act, personal income tax is progressive: the first '
                  '₦800,000 of taxable income is always 0%, and each higher slice of income is '
                  'taxed only at the rate for its own band. Your pension contribution and rent '
                  'relief reduce your taxable income before any band is applied, which is why '
                  'your effective rate (${profile.effectiveTaxRate.toStringAsFixed(1)}%) is lower than your top band rate.',
                  style: t(size: 10, color: _grey),
                ),
              ],
            ),
          ),
          pw.SizedBox(height: 16),

          // ── All bands reference ────────────────────────────────────────
          pw.Text('All 2025 bands at a glance', style: pw.TextStyle(font: boldFont, fontSize: 13)),
          pw.SizedBox(height: 6),
          pw.Table(
            columnWidths: {
              0: const pw.FlexColumnWidth(3),
              1: const pw.FlexColumnWidth(1.2),
              2: const pw.FlexColumnWidth(4.5),
            },
            children: [
              pw.TableRow(
                decoration: const pw.BoxDecoration(color: PdfColor.fromInt(0xFF00288E)),
                children: ['Taxable income band', 'Rate', 'What it means']
                    .map((h) => pw.Padding(
                          padding: const pw.EdgeInsets.all(6),
                          child: pw.Text(h,
                              style: pw.TextStyle(
                                  font: boldFont, fontSize: 10, color: PdfColors.white)),
                        ))
                    .toList(),
              ),
              ...kNtaBands.map((band) {
                final inUse = topBand != null && band.rate == topBand.rate;
                return pw.TableRow(
                  decoration: inUse
                      ? pw.BoxDecoration(color: _softBg)
                      : const pw.BoxDecoration(),
                  children: [
                    pw.Padding(
                      padding: const pw.EdgeInsets.all(6),
                      child: pw.Text(band.label, style: t(bold: inUse, size: 10)),
                    ),
                    pw.Padding(
                      padding: const pw.EdgeInsets.all(6),
                      child: pw.Text('${(band.rate * 100).toStringAsFixed(0)}%',
                          style: t(bold: true, size: 10, color: _primary)),
                    ),
                    pw.Padding(
                      padding: const pw.EdgeInsets.all(6),
                      child: pw.Text(_bandMeaning(band), style: t(size: 9, color: _grey)),
                    ),
                  ],
                );
              }),
            ],
          ),
          pw.SizedBox(height: 16),

          // ── CIT note (only when meaningful) ────────────────────────────
          if (!profile.citExemption.startsWith('N/A')) ...[
            pw.Text('Company Income Tax (CIT) status', style: pw.TextStyle(font: boldFont, fontSize: 13)),
            pw.SizedBox(height: 4),
            pw.Text(
              profile.citExemption.replaceAll('_', ' '),
              style: t(
                size: 11,
                color: profile.citExemption.contains('EXEMPT')
                    ? _green
                    : _red,
              ),
            ),
            pw.SizedBox(height: 16),
          ],

          // ── Disclaimer ─────────────────────────────────────────────────
          pw.Container(
            padding: const pw.EdgeInsets.all(12),
            decoration: pw.BoxDecoration(
              color: _softBg,
              borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
            ),
            child: pw.Text(
              'Disclaimer: This report is generated for educational purposes and does not '
              'constitute professional tax advice. Figures reflect your inputs and the 2025 '
              'Nigeria Tax Act as implemented by NaijaTax Enlighten. Please consult a '
              'registered tax practitioner for official filings.',
              style: pw.TextStyle(fontSize: 9, font: font, color: _grey),
            ),
          ),
        ],
      ),
    );

    return doc.save();
  }

  static Future<void> exportTaxReport(TaxProfile profile, {String? userName}) async {
    final bytes = await generateTaxReportBytes(profile, userName: userName);
    final nameSlug = (userName ?? '').trim().isEmpty
        ? 'Tax_Report'
        : 'Tax_Report_${userName!.trim().replaceAll(RegExp(r'[^A-Za-z0-9]+'), '_')}';
    await Printing.sharePdf(bytes: bytes, filename: '$nameSlug.pdf');
  }

  // ── Helpers ──────────────────────────────────────────────────────────────

  /// Human range for a marginal rate, derived from the canonical bands.
  static String? _rangeForRate(double ratePct) {
    double start = 0;
    for (final band in kNtaBands) {
      if ((band.rate * 100).round() == ratePct.round()) {
        if (band.rate == 0) return 'the first ${TaxHints.compactNaira(band.width)}';
        if (band.width == double.infinity) {
          return 'more than ${TaxHints.compactNaira(start)}';
        }
        return '${TaxHints.compactNaira(start)} and ${TaxHints.compactNaira(start + band.width)}';
      }
      start += band.width;
    }
    return null;
  }

  static String _bandMeaning(TaxBand band) {
    if (band.rate == 0) return 'Completely tax-free';
    final pct = '${(band.rate * 100).toStringAsFixed(0)}%';
    if (band.width == double.infinity) return 'Everything above ₦50M pays $pct';
    return 'Each slice inside this range pays $pct';
  }

  static pw.Widget _heroCell(
    String label,
    String value,
    PdfColor valueColor,
    pw.TextStyle Function({bool bold, double size, PdfColor? color}) t, {
    bool isLast = false,
  }) {
    return pw.Expanded(
      child: pw.Container(
        padding: const pw.EdgeInsets.symmetric(horizontal: 6),
        decoration: isLast
            ? null
           : pw.BoxDecoration(
                border: pw.Border(right: pw.BorderSide(color: _line)),
              ),
        child: pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(label, style: t(size: 8.5, color: _grey)),
            pw.SizedBox(height: 3),
            pw.Text(value, style: t(bold: true, size: 13, color: valueColor)),
          ],
        ),
      ),
    );
  }

  static pw.Widget _stepRow(String label, String value, pw.TextStyle Function({bool bold, double size, PdfColor? color}) t) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 3),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Flexible(child: pw.Text(label, style: t(size: 11))),
          pw.SizedBox(width: 8),
          pw.Text(value, style: t(size: 11)),
        ],
      ),
    );
  }
}
